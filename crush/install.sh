#!/bin/sh
# Writes Venom's Crush hooks into your global crushrc with absolute paths.
#
#   sh crush/install.sh            print the hook lines
#   sh crush/install.sh --apply    write ~/.config/crush/venom.crushrc and add
#                                  one "source" line to ~/.config/crush/crushrc
#
# Crush runs hook commands from the project directory, so a global hook needs an
# absolute path to this folder: run this from wherever you keep the clone.
here=$(cd "$(dirname "$0")" && pwd)
hook="$here/hooks/crush-hook.sh"
chmod +x "$hook" "$here/hooks/venom-hook.sh" 2>/dev/null
cfg="${CRUSH_GLOBAL_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/crush}"
lines="# Venom hooks for Crush (generated by crush/install.sh)
hook add PreToolUse --name venom-context --command \"$hook pre-tool\" --timeout 10
hook add PostToolUse --name venom-milestones --matcher '^(bash|mcp_.*(append_task_log|append_project_log|edit_log_entry))\$' --command \"$hook post-tool\" --timeout 10
hook add PostCompact --name venom-compacted --command \"$hook mark-compacted\" --timeout 10"
if [ "${1:-}" != "--apply" ]; then
  printf '%s\n' "$lines"
  exit 0
fi
mkdir -p "$cfg" || exit 1
printf '%s\n' "$lines" > "$cfg/venom.crushrc"
if ! grep -qF "venom.crushrc" "$cfg/crushrc" 2>/dev/null; then
  printf '\nsource "%s/venom.crushrc"\n' "$cfg" >> "$cfg/crushrc"
fi
echo "Venom hooks added: $cfg/venom.crushrc (sourced from $cfg/crushrc)"
